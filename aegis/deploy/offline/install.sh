#!/usr/bin/env bash
# Installs AEGIS from an offline bundle on a machine with Docker and no internet access.
#
#   ./install.sh                 verify the bundle, load images, create .env, start AEGIS
#   ./install.sh --demo          the same, then seed the synthetic demo tenant
#   ./install.sh --host aegis.entity.local   name users will type (default: this machine's hostname)
#   ./install.sh check           health of every service
#   ./install.sh verify-offline  prove the AEGIS containers cannot reach the internet
#   ./install.sh stop | start | logs
#
# Needs: Docker Engine with the compose plugin, openssl, sha256sum. Nothing is downloaded.
set -euo pipefail
cd "$(dirname "$0")"
DC=(docker compose --env-file .env -f docker-compose.yml)

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

wait_healthy() {
  say "waiting for the console and the gateway..."
  for _ in $(seq 1 120); do
    if curl -fsS -o /dev/null http://127.0.0.1:4000/health 2>/dev/null && curl -fsS -o /dev/null http://127.0.0.1:3000/login 2>/dev/null; then
      say "AEGIS is up."
      return 0
    fi
    sleep 2
  done
  "${DC[@]}" ps
  die "AEGIS did not become healthy in 4 minutes; see ./install.sh logs"
}

check() {
  "${DC[@]}" ps
  curl -fsS http://127.0.0.1:4000/health >/dev/null && say "gateway: ok" || say "gateway: NOT responding"
  curl -fsS -o /dev/null http://127.0.0.1:3000/login && say "console: ok" || say "console: NOT responding"
}

verify_offline() {
  # Each AEGIS container tries to open a connection to a public address. Every attempt must fail.
  local failed=0
  for svc in api worker web; do
    if "${DC[@]}" exec -T "$svc" node -e "const s=require('net').connect({host:'1.1.1.1',port:443,timeout:4000});s.on('connect',()=>{console.log('REACHED');process.exit(0)});s.on('error',()=>process.exit(3));s.on('timeout',()=>process.exit(3))" >/dev/null 2>&1; then
      say "$svc: CAN reach the internet"; failed=1
    else
      say "$svc: no route to the internet (as intended)"
    fi
  done
  [ "$failed" = 0 ] || die "a container reached the internet; check that the core network is internal"
}

case "${1:-install}" in
  check) check; exit 0 ;;
  verify-offline) verify_offline; exit 0 ;;
  stop) "${DC[@]}" down; exit 0 ;;
  start) "${DC[@]}" up -d; wait_healthy; exit 0 ;;
  logs) "${DC[@]}" logs --tail 200 -f; exit 0 ;;
esac

DEMO=0
HOST="$(hostname -f 2>/dev/null || hostname)"
while [ $# -gt 0 ]; do
  case "$1" in
    install) ;;
    --demo) DEMO=1 ;;
    --host) shift; HOST="${1:?--host needs a name}" ;;
    *) die "unknown option $1" ;;
  esac
  shift
done

command -v docker >/dev/null || die "Docker is not installed"
docker compose version >/dev/null 2>&1 || die "the Docker compose plugin is not installed"
command -v openssl >/dev/null || die "openssl is not installed"
command -v curl >/dev/null || die "curl is not installed"

say "1/5 verifying the bundle"
sha256sum -c SHA256SUMS --quiet || die "bundle checksum mismatch; do not install this copy"
VERSION="$(cat VERSION)"

say "2/5 loading images (no network needed)"
docker load -i images.tar.gz | sed 's/^/  /'

say "3/5 configuring"
if [ ! -f .env ]; then
  OWNER_PW=$(openssl rand -hex 24); APP_PW=$(openssl rand -hex 24)
  TLS=internal
  if [ -f certs/cert.pem ] && [ -f certs/key.pem ]; then TLS="/certs/cert.pem /certs/key.pem"; fi
  umask 077
  cat > .env <<ENV
# Generated by install.sh. Keep this file private: it holds the database passwords and the master keys.
AEGIS_VERSION=${VERSION}
AEGIS_HOST=${HOST}
AEGIS_TLS=${TLS}
POSTGRES_OWNER_PASSWORD=${OWNER_PW}
POSTGRES_APP_PASSWORD=${APP_PW}
NODE_ENV=production
AEGIS_DEMO_MODE=$([ "$DEMO" = 1 ] && echo true || echo false)
AEGIS_MASTER_KEY=$(openssl rand -base64 32)
AEGIS_SESSION_SECRET=$(openssl rand -base64 32)
EVIDENCE_SIGNING_KEY=$(openssl genpkey -algorithm ed25519 | base64 | tr -d '\n')
API_PORT=4000
WEB_PUBLIC_URL=https://${HOST}
API_PUBLIC_URL=https://${HOST}:8443
API_CORS_ORIGINS=https://${HOST},http://localhost:3000
AEGIS_STORAGE_DIR=/data/uploads
AEGIS_EMAIL_NOTIFICATIONS=false
OTEL_EXPORTER_OTLP_ENDPOINT=
LOG_LEVEL=info
AEGIS_DEPLOYMENT_MANIFEST=
ENV
  say "  wrote .env (mode 600) with new passwords and keys"
else
  say "  keeping the existing .env"
fi
mkdir -p certs seed-output

say "4/5 starting AEGIS"
"${DC[@]}" up -d
wait_healthy

if [ "$DEMO" = 1 ]; then
  say "  seeding the synthetic demo tenant"
  "${DC[@]}" --profile seed run --rm seed
fi

say "5/5 checking that AEGIS has no route to the internet"
verify_offline

say ""
say "Console:  https://${HOST}        (on this machine: http://localhost:3000)"
say "Gateway:  https://${HOST}:8443   (on this machine: http://localhost:4000)"
[ "$DEMO" = 1 ] && say "Demo sign-in details: seed-output/.demo-keys.json (keep it private)"
say "With Caddy's internal certificate, browsers warn until the entity trusts its root:"
say "  docker compose --env-file .env cp proxy:/data/caddy/pki/authorities/local/root.crt ./aegis-root.crt"
