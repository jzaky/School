"use client";
import * as React from "react";
import { useRouter } from "next/navigation";
import { toast } from "sonner";
import { Plus, Save } from "lucide-react";
import { buildTradingPolicyDocument, explainTradingPolicy, type TradingTemplateSettings } from "@aegis/core/policy/trading";
import type { PolicyDocument } from "@aegis/core/policy/schema";
import { createVersionAction, saveDraftAction } from "@/server/actions/policies";
import { Button } from "@/components/ui/button";
import { Dialog } from "@/components/ui/dialog";
import { Field, FormError, Textarea } from "@/components/ui/input";
import { Panel } from "@/components/ui/panel";
import { Note } from "@/components/ui/note";
import { RefundExplanation, type RoleOption, type ToolOptionLite } from "./policy-refund-form";
import { parseTradingForm, TradingSamplePreview, TradingSettingsForm, valuesFromTradingSettings } from "./policy-trading-form";
import { PolicyReplayPanel } from "./policy-replay";
import type { ThresholdsVersion } from "./policy-thresholds";

/** Guided editing of a trading mandate generated by the template. Saves through the normal draft and version flow. */
export function TradingMandatePanel({ policyId, version, settings, diverged, roles, tools, canWrite }: { policyId: string; version: ThresholdsVersion; settings: TradingTemplateSettings; diverged: boolean; roles: RoleOption[]; tools: ToolOptionLite[]; canWrite: boolean }) {
  const router = useRouter();
  const initial = React.useMemo(() => valuesFromTradingSettings(settings), [settings]);
  const [values, setValues] = React.useState(initial);
  React.useEffect(() => setValues(initial), [initial]);
  const parsed = React.useMemo(() => parseTradingForm(values), [values]);
  const document = React.useMemo<PolicyDocument | null>(() => (parsed.settings ? buildTradingPolicyDocument(parsed.settings) : null), [parsed.settings]);
  const explanation = React.useMemo(() => (parsed.settings ? explainTradingPolicy(parsed.settings) : []), [parsed.settings]);
  const dirty = JSON.stringify(values) !== JSON.stringify(initial);
  const isDraft = version.state === "draft";
  const [saving, setSaving] = React.useState(false);
  const [newVersionOpen, setNewVersionOpen] = React.useState(false);
  const [note, setNote] = React.useState("");
  const [nvError, setNvError] = React.useState<string | null>(null);

  const defaultNote = React.useMemo(() => {
    if (!parsed.settings) return "";
    const s = parsed.settings;
    return `Trading mandate: automatic below ${s.currency} ${s.autoApproveNotionalBelow}, approval up to ${s.currency} ${s.approvalNotionalUpTo}, ${s.instruments.length} instruments`;
  }, [parsed.settings]);

  async function saveDraft() {
    if (!document) return;
    setSaving(true);
    const r = await saveDraftAction(policyId, version.id, { document, changeNote: defaultNote || undefined });
    setSaving(false);
    if (!r.ok) return toast.error(r.error);
    toast.success(`Draft v${version.version} saved`);
    router.refresh();
  }
  async function createVersion(e: React.FormEvent) {
    e.preventDefault();
    if (!document) return;
    setSaving(true);
    setNvError(null);
    const r = await createVersionAction(policyId, { document, changeNote: note.trim() || defaultNote });
    setSaving(false);
    if (!r.ok) return setNvError(r.error);
    toast.success(`Draft v${r.data.version} created`);
    setNewVersionOpen(false);
    setNote("");
    router.push(`/policies/${policyId}?v=${r.data.versionId}&tab=thresholds`);
  }

  const saveDisabledReason = !canWrite ? "Requires policies:write" : !document ? "Fix the highlighted fields first" : !dirty ? "No changes to save" : undefined;

  return (
    <div className="space-y-4" data-testid="trading-mandate">
      {!isDraft ? (
        <Note>
          Version v{version.version} is {version.state} and frozen. Changing the mandate creates a new draft version that still goes through review and a second person&apos;s activation.
        </Note>
      ) : !canWrite ? (
        <Note>You can explore the mandate, but saving requires policies:write.</Note>
      ) : null}
      {diverged ? <Note tone="warning">The JSON of this version was edited by hand after it was generated. Saving from this form regenerates every rule from the settings below and drops those manual edits. Use the Editor tab to keep them.</Note> : null}
      <div className="grid gap-4 xl:grid-cols-2">
        <Panel
          title="Trading mandate"
          description="What the agent may trade, how much runs on its own, and what waits for a person. The JSON stays editable in the Editor tab."
          actions={
            isDraft ? (
              <Button size="sm" variant="primary" onClick={saveDraft} loading={saving} disabled={!!saveDisabledReason} disabledReason={saveDisabledReason}>
                <Save className="h-3.5 w-3.5" aria-hidden />
                Save draft
              </Button>
            ) : (
              <Button size="sm" variant="primary" onClick={() => setNewVersionOpen(true)} disabled={!canWrite || !document || !dirty} disabledReason={saveDisabledReason}>
                <Plus className="h-3.5 w-3.5" aria-hidden />
                New draft version
              </Button>
            )
          }
        >
          <TradingSettingsForm values={values} onChange={setValues} errors={parsed.errors} roles={roles} tools={tools} idPrefix="trm" />
        </Panel>
        <div className="space-y-4">
          <Panel title="What this mandate does" description="Generated from the settings. Changes appear immediately.">
            {explanation.length ? <RefundExplanation lines={explanation} /> : <p className="text-xs text-deny">Fix the highlighted fields to see the explanation.</p>}
          </Panel>
          <Panel title="Sample orders" description="Dry runs of one order per band and guard against the settings as they stand now.">
            <TradingSamplePreview settings={parsed.settings} />
          </Panel>
          <Note>AEGIS does not trade and holds no strategy. The agent decides what to order; this mandate decides what may reach the broker, what waits for a person and what is refused. Paper trading only: the Alpaca connector refuses live keys.</Note>
        </div>
      </div>

      <PolicyReplayPanel policyId={policyId} versionId={version.id} versionLabel={`v${version.version}`} document={dirty ? document : undefined} title="What would this mandate have done?" description={dirty ? "Replays recent orders against the unsaved mandate above. Nothing is recorded." : `Replays recent orders against v${version.version}. Change a limit above to compare a draft. Nothing is recorded.`} />

      <Dialog
        open={newVersionOpen}
        onOpenChange={(o) => {
          setNewVersionOpen(o);
          if (!o) setNvError(null);
        }}
        title="New draft version from this mandate"
        description={`Creates v${version.version + 1} as a draft. v${version.version} stays unchanged until the draft is reviewed and activated by someone else.`}
        size="sm"
        footer={
          <>
            <Button variant="ghost" onClick={() => setNewVersionOpen(false)} disabled={saving}>
              Cancel
            </Button>
            <Button form="trading-new-version" type="submit" variant="primary" loading={saving}>
              Create draft
            </Button>
          </>
        }
      >
        <form id="trading-new-version" onSubmit={createVersion} className="space-y-3">
          <Field label="Change note" htmlFor="trm-nv-note" hint="shown in history">
            <Textarea id="trm-nv-note" value={note} onChange={(e) => setNote(e.target.value)} maxLength={500} autoFocus placeholder={defaultNote} />
          </Field>
          <FormError error={nvError} />
        </form>
      </Dialog>
    </div>
  );
}
