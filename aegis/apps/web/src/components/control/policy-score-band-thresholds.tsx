"use client";
import * as React from "react";
import { useRouter } from "next/navigation";
import { toast } from "sonner";
import { Plus, Save } from "lucide-react";
import { buildScoreBandPolicyDocument, explainScoreBandPolicy, type ScoreBandSettings } from "@aegis/core/policy/score-band";
import type { PolicyDocument } from "@aegis/core/policy/schema";
import { createVersionAction, saveDraftAction } from "@/server/actions/policies";
import { Button } from "@/components/ui/button";
import { Dialog } from "@/components/ui/dialog";
import { Field, FormError, Textarea } from "@/components/ui/input";
import { Panel } from "@/components/ui/panel";
import { Note } from "@/components/ui/note";
import { RefundExplanation, type RoleOption, type ToolOptionLite } from "./policy-refund-form";
import { parseScoreBandForm, ScoreBandSamplePreview, ScoreBandSettingsForm, valuesFromScoreBandSettings } from "./policy-score-band-form";
import { PolicyReplayPanel } from "./policy-replay";
import type { ThresholdsVersion } from "./policy-thresholds";

/** Guided editing of a score-band policy generated by the template. Saves through the normal draft and version flow. */
export function ScoreBandThresholdsPanel({ policyId, version, settings, diverged, roles, tools, canWrite }: { policyId: string; version: ThresholdsVersion; settings: ScoreBandSettings; diverged: boolean; roles: RoleOption[]; tools: ToolOptionLite[]; canWrite: boolean }) {
  const router = useRouter();
  const initial = React.useMemo(() => valuesFromScoreBandSettings(settings), [settings]);
  const [values, setValues] = React.useState(initial);
  React.useEffect(() => setValues(initial), [initial]);
  const parsed = React.useMemo(() => parseScoreBandForm(values), [values]);
  const document = React.useMemo<PolicyDocument | null>(() => (parsed.settings ? buildScoreBandPolicyDocument(parsed.settings) : null), [parsed.settings]);
  const explanation = React.useMemo(() => (parsed.settings ? explainScoreBandPolicy(parsed.settings) : []), [parsed.settings]);
  const dirty = JSON.stringify(values) !== JSON.stringify(initial);
  const isDraft = version.state === "draft";
  const [saving, setSaving] = React.useState(false);
  const [newVersionOpen, setNewVersionOpen] = React.useState(false);
  const [note, setNote] = React.useState("");
  const [nvError, setNvError] = React.useState<string | null>(null);

  const defaultNote = React.useMemo(() => {
    if (!parsed.settings) return "";
    const s = parsed.settings;
    return `Score bands: review from ${s.reviewFrom}, hold from ${s.holdFrom}, block from ${s.blockFrom} (${s.scoreAttribute})`;
  }, [parsed.settings]);

  async function saveDraft() {
    if (!document) return;
    setSaving(true);
    const r = await saveDraftAction(policyId, version.id, { document, changeNote: defaultNote || undefined });
    setSaving(false);
    if (!r.ok) return toast.error(r.error);
    toast.success(`Draft v${version.version} saved`);
    router.refresh();
  }
  async function createVersion(e: React.FormEvent) {
    e.preventDefault();
    if (!document) return;
    setSaving(true);
    setNvError(null);
    const r = await createVersionAction(policyId, { document, changeNote: note.trim() || defaultNote });
    setSaving(false);
    if (!r.ok) return setNvError(r.error);
    toast.success(`Draft v${r.data.version} created`);
    setNewVersionOpen(false);
    setNote("");
    router.push(`/policies/${policyId}?v=${r.data.versionId}&tab=thresholds`);
  }

  const saveDisabledReason = !canWrite ? "Requires policies:write" : !document ? "Fix the highlighted fields first" : !dirty ? "No changes to save" : undefined;

  return (
    <div className="space-y-4" data-testid="score-band-thresholds">
      {!isDraft ? (
        <Note>
          Version v{version.version} is {version.state} and can no longer be changed. Changing the bands creates a new draft version, which still goes through review and must be switched on by a second person.
        </Note>
      ) : !canWrite ? (
        <Note>You can explore the bands, but saving needs the policies:write permission.</Note>
      ) : null}
      {diverged ? <Note tone="warning">Someone edited this version&apos;s rules by hand (in the JSON) after the form generated them. Saving from this form rebuilds every rule from the settings below and discards those manual edits. To keep them, use the Editor tab instead.</Note> : null}
      <div className="grid gap-4 xl:grid-cols-2">
        <Panel
          title="Score bands"
          description="Your model's score, routed into clear, review, hold and block. The underlying rules (JSON) stay editable in the Editor tab."
          actions={
            isDraft ? (
              <Button size="sm" variant="primary" onClick={saveDraft} loading={saving} disabled={!!saveDisabledReason} disabledReason={saveDisabledReason}>
                <Save className="h-3.5 w-3.5" aria-hidden />
                Save draft
              </Button>
            ) : (
              <Button size="sm" variant="primary" onClick={() => setNewVersionOpen(true)} disabled={!canWrite || !document || !dirty} disabledReason={saveDisabledReason}>
                <Plus className="h-3.5 w-3.5" aria-hidden />
                New draft version
              </Button>
            )
          }
        >
          <ScoreBandSettingsForm values={values} onChange={setValues} errors={parsed.errors} roles={roles} tools={tools} idPrefix="sbt" />
        </Panel>
        <div className="space-y-4">
          <Panel title="What this policy does" description="Written from the settings on the left. Changes appear immediately.">
            {explanation.length ? <RefundExplanation lines={explanation} /> : <p className="text-xs text-deny">Fix the highlighted fields to see the explanation.</p>}
          </Panel>
          <Panel title="Sample requests" description="One sample request for each band, tried against the settings as they stand now (a dry run).">
            <ScoreBandSamplePreview settings={parsed.settings} />
          </Panel>
          <Note>
            How the agent sends the score: {parsed.settings?.scoreSource === "params" ? `as params.${parsed.settings.scoreAttribute}` : `as context.${parsed.settings?.scoreAttribute ?? "riskScore"}`} on each request. The model stays yours; AEGIS only reads the number.
          </Note>
        </div>
      </div>

      <PolicyReplayPanel policyId={policyId} versionId={version.id} versionLabel={`v${version.version}`} document={dirty ? document : undefined} title="What would these bands have done?" description={dirty ? "Replays recent requests against the unsaved bands above. Nothing is recorded." : `Replays recent requests against v${version.version}. Change a band above to compare a draft. Nothing is recorded.`} />

      <Dialog
        open={newVersionOpen}
        onOpenChange={(o) => {
          setNewVersionOpen(o);
          if (!o) setNvError(null);
        }}
        title="New draft version from these bands"
        description={`Creates v${version.version + 1} as a draft. v${version.version} stays in force, unchanged, until the draft is reviewed and switched on by someone else.`}
        size="sm"
        footer={
          <>
            <Button variant="ghost" onClick={() => setNewVersionOpen(false)} disabled={saving}>
              Cancel
            </Button>
            <Button form="score-band-new-version" type="submit" variant="primary" loading={saving}>
              Create draft
            </Button>
          </>
        }
      >
        <form id="score-band-new-version" onSubmit={createVersion} className="space-y-3">
          <Field label="Change note" htmlFor="sbt-nv-note" hint="a short note on what changed, shown in the version history">
            <Textarea id="sbt-nv-note" value={note} onChange={(e) => setNote(e.target.value)} maxLength={500} autoFocus placeholder={defaultNote} />
          </Field>
          <FormError error={nvError} />
        </form>
      </Dialog>
    </div>
  );
}
