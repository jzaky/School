export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, ar };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = MESSAGES[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function navLabel(locale: Locale, english: string): string {
  return locale === "ar" ? (NAV_AR[english] ?? english) : english;
}

