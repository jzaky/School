const reqUrl = (await import("node:fs")).readFileSync("/tmp/claude-0/hero1-url.txt", "utf8").replace("?submitted=1", "");
await p.goto(reqUrl);
console.log("request status:", await p.locator("[data-testid=request-title] + div").textContent());
// Rania got an update
await p.click("[data-testid=persona-switcher]");
await p.click("[data-testid=persona-parent]");
await p.waitForURL(/home/, { timeout: 120000 });
await p.click("[data-testid=notifications-bell]");
await p.waitForTimeout(1500);
